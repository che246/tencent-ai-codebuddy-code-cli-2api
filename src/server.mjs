// 请求体 50MB 保护上限，防止超大 Prompt 或大量 base64 图片引发 V8 OOM 崩溃
const MAX_REQUEST_BODY_BYTES = 50 * 1024 * 1024;

/**
 * 统一处理请求处理器抛出的异常（P0 兜底）。
 *
 * 关键分支：
 *   · 响应头尚未发送 → 返回 500 JSON，客户端能拿到明确错误；
 *   · 响应头已发送（典型：SSE 流已开始）→ 不能再 writeHead，否则会抛
 *     ERR_HTTP_HEADERS_SENT 引发第二次异常；此时只尝试结束流并记录。
 */
function handleRequestFailure(res, err) {
  const message = err instanceof Error ? err.message : String(err);
  Logger.error('SERVER', `请求处理器异常: ${message}`);

  try {
    if (res.writableEnded) return;
    if (res.headersSent) {
      // 已经在流式输出中途，无法再改状态码；尽力收尾，避免连接悬挂
      try { res.end(); } catch (_) {}
      return;
    }
    res.writeHead(500, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: { message: 'Internal gateway error', type: 'api_error' } }));
  } catch (e) {
    Logger.error('SERVER', `请求处理器异常后收尾失败: ${e instanceof Error ? e.message : String(e)}`);
    try { res.destroy(); } catch (_) {}
  }
}

/**
 * 安全读取请求体并分发给处理器，带 Content-Length 预检、实时字节流限额以及底层 Socket 错误保护
 */
function readRequestBody(req, res, handler, maxBytes = MAX_REQUEST_BODY_BYTES) {
  const contentLength = parseInt(req.headers['content-length'] || '0', 10);
  if (contentLength > maxBytes) {
    res.writeHead(413, { 'Content-Type': 'application/json' });
    return res.end(JSON.stringify({ error: { message: `Payload too large (max ${maxBytes / 1024 / 1024}MB)`, type: 'payload_too_large' } }));
  }

  let rawBody = '';
  let receivedBytes = 0;
  let aborted = false;

  req.on('data', chunk => {
    if (aborted) return;
    receivedBytes += chunk.length;
    if (receivedBytes > maxBytes) {
      aborted = true;
      req.destroy();
      if (!res.writableEnded) {
        res.writeHead(413, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ error: { message: `Payload too large (exceeded ${maxBytes / 1024 / 1024}MB limit)`, type: 'payload_too_large' } }));
      }
      return;
    }
    rawBody += chunk;
  });

  req.on('end', () => {
    if (aborted) return;
    // handler 是 async 函数，必须显式接住 rejection。
    // 之前这里直接 `handler(req, res, rawBody)`，返回值 Promise 被丢弃，
    // 任何内部异常都会变成 unhandledRejection 并终止进程（P0）。
    Promise.resolve()
      .then(() => handler(req, res, rawBody))
      .catch(err => handleRequestFailure(res, err));
  });

  req.on('error', (err) => {
    if (aborted) return;
    aborted = true;
    Logger.error('SERVER', `读取客户端请求流异常: ${err.message}`);
    if (!res.writableEnded) {
      res.writeHead(400, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: { message: 'Failed to read request stream', type: 'bad_request' } }));
    }
  });
}

// 2. HTTP 服务与路由总线
const server = http.createServer(async (req, res) => {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', '*');
  if (req.method === 'OPTIONS') {
    res.writeHead(200);
    return res.end();
  }

  const url = new URL(req.url, `http://${req.headers.host}`);

  // 1. Web 控制台静态单页
  if (url.pathname === '/' || url.pathname === '/index.html') {
    return handleDashboard(req, res);
  }

  // 2. 探活路由
  //    uptimeMs / startedAt 用于外部监控与 Web 控制台展示网关连续运行时长。
  //    取 process.uptime() 而非自记时间戳：它是 Node 进程真实存活秒数，不受系统时钟回拨影响。
  if (url.pathname === '/healthz') {
    const uptimeMs = Math.round(process.uptime() * 1000);
    res.writeHead(200, { 'Content-Type': 'application/json' });
    return res.end(JSON.stringify({
      status: 'ok',
      activeAccounts: accounts.filter(a => a.status === 'healthy').length,
      uptimeMs,
      uptime: formatUptime(uptimeMs),
      startedAt: new Date(Date.now() - uptimeMs).toISOString()
    }));
  }

  // 3. API 鉴权 (多 Key 校验，同时支持 Authorization: Bearer 和 x-api-key，常量时间安全比对)
  const isApiPath = url.pathname.startsWith('/v1/') || url.pathname === '/messages' || url.pathname === '/search' || url.pathname === '/fetch';
  if (isApiPath) {
    const authHeader = req.headers['authorization'] || '';
    const xApiKey = req.headers['x-api-key'] || '';
    const token = authHeader.replace(/^Bearer\s+/i, '') || xApiKey;
    if (!isValidApiKey(token)) {
      Logger.warn('AUTH', `非法 API Key 访问: ${url.pathname}`, { ip: req.socket.remoteAddress });
      res.writeHead(401, { 'Content-Type': 'application/json' });
      return res.end(JSON.stringify({ error: { message: 'Invalid API Key', type: 'auth_error' } }));
    }
  }

  // 4. GET /v1/models (标准 OpenAI 模型列表)
  //    支持 ?region=cn|intl|both|all 或 X-Region 头做区域区分
  if (req.method === 'GET' && url.pathname === '/v1/models') {
    return handleOpenAiModels(req, res, url);
  }

  // 5. 官方免费服务端联网检索: POST /v1/search & POST /search
  if (req.method === 'POST' && (url.pathname === '/v1/search' || url.pathname === '/search')) {
    return readRequestBody(req, res, handleSearch);
  }

  // 6. 官方免费服务端网页抓取: POST /v1/fetch & POST /fetch
  if (req.method === 'POST' && (url.pathname === '/v1/fetch' || url.pathname === '/fetch')) {
    return readRequestBody(req, res, handleWebFetch);
  }

  // 7. Anthropic 协议适配: POST /v1/messages & POST /messages
  if (req.method === 'POST' && (url.pathname === '/v1/messages' || url.pathname === '/messages')) {
    return readRequestBody(req, res, handleAnthropicMessages);
  }

  // 8. OpenAI 协议适配: POST /v1/chat/completions
  if (req.method === 'POST' && url.pathname === '/v1/chat/completions') {
    return readRequestBody(req, res, handleOpenAiChatCompletions);
  }

  // 9. /api/* 运维与管理 REST API
  if (url.pathname.startsWith('/api/')) {
    return handleApiRoutes(req, res, url);
  }

  res.writeHead(404, { 'Content-Type': 'application/json' });
  return res.end(JSON.stringify({ error: 'Endpoint not found' }));
});

